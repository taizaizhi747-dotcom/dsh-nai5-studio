function runSyntaxChecks() {
  const targets = [
    path.join(ROOT_DIR, 'index.js'),
    CLIENT_JS_OUT,
    path.join(ROOT_DIR, 'mcp_server.mjs'),
    __filename
  ];
  for (const fn of fs.readdirSync(LIB_DIR).sort()) {
    if (fn.endsWith('.js') || fn.endsWith('.mjs')) {
      targets.push(path.join(LIB_DIR, fn));
    }
  }
  if (fs.existsSync(TESTS_DIR)) {
    for (const fn of fs.readdirSync(TESTS_DIR).sort()) {
      if (fn.endsWith('.mjs') || fn.endsWith('.js')) {
        targets.push(path.join(TESTS_DIR, fn));
      }
    }
  }

  for (const file of targets) {
    const res = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
    if (res.status !== 0) {
      console.error(`Syntax check failed for ${file}:\n${res.stderr || res.stdout}`);
      process.exit(res.status || 1);
    }
  }
  console.log(`node --check passed for ${targets.length} files`);
}

function main() {
  const checkOnly = process.argv.includes('--check-only');
  if (!checkOnly) {
    buildClientBundle();
    buildCordisPatch();
  }
  runSyntaxChecks();
}

main();
